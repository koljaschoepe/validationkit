export async function snoozeFinding(
  userId: string,
  findingId: string,
  duration: "24h" | "7d" | "forever",
): Promise<ApplyResult> {
  if (!isDbEnabled()) return { ok: false, error: "DB not configured." };
  const db = getDb();
  const findingRows = await db
    .select({ finding: schema.finding, scan: schema.scan })
    .from(schema.finding)
    .innerJoin(schema.scan, eq(schema.finding.scanId, schema.scan.id))
    .where(eq(schema.finding.id, findingId))
    .limit(1);
  const row = findingRows[0];
  if (!row) return { ok: false, error: "Finding not found." };
  if (!(await userIsMember(row.scan.workspaceId, userId))) {
    return { ok: false, error: "Not authorized." };
  }

  const until = snoozeDurationToDate(duration);
  await db
    .update(schema.finding)
    .set({
      dismissStatus: "snoozed",
      snoozedUntil: until,
      dismissReason: null,
    })
    .where(eq(schema.finding.id, findingId));

  await db.insert(schema.applyAction).values({
    findingId,
    workspaceId: row.scan.workspaceId,
    mode: "n/a",
    decision: "snooze",
    snoozeUntil: until,
    decidedBy: userId,
  });

  updateTag(galaxieWorkspaceTag(row.scan.workspaceId));
  return { ok: true };
}

export interface ApplyActionRow {
  id: string;
  mode: string;
  decision: string;
  reason: string | null;
  targetUrl: string | null;
  targetRef: string | null;
  targetStatus: string | null;
  snoozeUntil: Date | null;
  decidedAt: Date;
}

export async function listApplyActionsForFinding(
  findingId: string,
): Promise<ApplyActionRow[]> {
  if (!isDbEnabled()) return [];
  const db = getDb();
  // K11: gate by session-membership. Resolve the owning workspace
  // (finding → scan) and verify the caller is a member before returning the
  // apply history; empty array on denial.
  const user = await getSessionUser();
  if (!user) return [];
  const findingRows = await db
    .select({ workspaceId: schema.scan.workspaceId })
    .from(schema.finding)
    .innerJoin(schema.scan, eq(schema.finding.scanId, schema.scan.id))
    .where(eq(schema.finding.id, findingId))
    .limit(1);
  const workspaceId = findingRows[0]?.workspaceId;
  if (!workspaceId || !(await userIsMember(workspaceId, user.id))) return [];
  const rows = await db
    .select()
    .from(schema.applyAction)
    .where(eq(schema.applyAction.findingId, findingId))
    .orderBy(desc(schema.applyAction.decidedAt));
  return rows.map((r) => ({
    id: r.id,
    mode: r.mode,
    decision: r.decision,
    reason: r.reason,
    targetUrl: r.targetUrl,
    targetRef: r.targetRef,
    targetStatus: r.targetStatus,
    snoozeUntil: r.snoozeUntil,
    decidedAt: r.decidedAt,
  }));
}

export async function pollPRStatus(
  applyActionId: string,
): Promise<{ state: string } | null> {
  if (!isDbEnabled()) return null;
  const db = getDb();
  const rows = await db
    .select()
    .from(schema.applyAction)
    .where(eq(schema.applyAction.id, applyActionId))
    .limit(1);
  const row = rows[0];
  if (!row) return null;
  if (row.mode !== "pr") return { state: row.targetStatus ?? "n/a" };
  // GitHub-App-Path isn't wired yet (Sprint 0.11). Until then echo back the
  // last-seen status; G5 doesn't introduce live polling here.
  return { state: row.targetStatus ?? "unknown" };
}
